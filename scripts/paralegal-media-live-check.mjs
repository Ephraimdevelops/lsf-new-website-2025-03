import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { runDevelopment as run } from './test-support/named-development.mjs';
const root=path.resolve(import.meta.dirname,'..');
const fixture=JSON.parse(fs.readFileSync(path.join(root,'output/paralegal-revamp/development-journey.json'),'utf8'));
const caseId=fixture.caseId;
const detail=run('caseManagement:getCase',{caseId},'paralegal');
assert.ok(detail.case.summary.startsWith('TEST ONLY')&&!['closed','resolved','closed_unresolved'].includes(detail.case.status));
const url=run('caseManagement:generateVoiceMessageUploadUrl',{caseId},'paralegal');
const audio=fs.readFileSync('/tmp/paralegal-synthetic-voice.m4a');
const upload=await fetch(url,{method:'POST',headers:{'Content-Type':'audio/mp4'},body:audio});
assert.equal(upload.status,200,'managed scan upload');
const {storageId}=await upload.json();assert.ok(storageId);
const args={caseId,storageId,clientMessageId:`synthetic-media-${Date.now()}`,mimeType:'audio/mp4',durationMs:2000};
const messageId=run('caseManagement:sendVoiceMessage',args,'paralegal');
assert.equal(run('caseManagement:sendVoiceMessage',args,'paralegal'),messageId,'voice send retry');
const messages=run('caseManagement:listMessages',{caseId},'user');
const message=messages.find(m=>m._id===messageId);assert.ok(message?.audioUrl);
assert.equal((await fetch(message.audioUrl)).status,200,'beneficiary playback source');
assert.throws(()=>run('caseManagement:listMessages',{caseId},'provider_staff'),/access denied/);
const report={checkedAt:new Date().toISOString(),deployment:'joyous-spaniel-5',caseId,checks:{managedVoiceUpload:true,idempotentVoiceSend:true,beneficiaryPlaybackSource:true,unassignedProviderDenied:true},note:'Generated silence only; microphone hardware and permission prompts were not exercised.'};
fs.writeFileSync(path.join(root,'output/paralegal-revamp/media-development-journey.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report.checks));
